import { previewHostOf, slotPorts } from "./paths.utils";
import { originOf, type IPreviewSettings } from "./preview.config";

export interface IPreviewRoute {
  readonly slot: number;
  readonly host: string;
  readonly uiPort: number;
}

/** `https://s<N>.<domain>` (or the http form) as a browser opens it through the proxy. */
export const previewUrlOf = (
  slot: number,
  settings: IPreviewSettings
): string => originOf(settings, previewHostOf(slot, settings.domain));

/** Where the login lives: one host for every slot, so one cookie covers them all. */
export const authUrlOf = (settings: IPreviewSettings): string =>
  originOf(settings, `auth.${settings.domain}`);

/** The UI address a person opens directly, no proxy needed. */
export const directUrlOf = (slot: number): string =>
  `http://127.0.0.1:${String(slotPorts(slot).ui)}`;

/** Upstream name of oauth2-proxy on the compose network (service `oauth2-proxy`). */
const OAUTH2_UPSTREAM = "http://oauth2-proxy:4180";

const authHttpBlock = `# Login gate (PREVIEW_AUTH_PROVIDER). Docker's DNS resolves the upstream
# at request time, so nginx starts even while the auth service is down.
resolver 127.0.0.11 valid=10s ipv6=off;
map $http_x_forwarded_proto $forwarded_proto {
  default $http_x_forwarded_proto;
  ''      $scheme;
}`;

/**
 * The two locations every gated slot gets. `/oauth2/auth` is internal: nginx
 * asks oauth2-proxy before serving the app. Anything it refuses is a 401 (sent
 * to the login) or a 403 (signed in, but not allowed in).
 */
const authSlotLocations = (
  settings: IPreviewSettings
): string => `  location = /oauth2/auth {
    internal;
    set $oauth2_upstream ${OAUTH2_UPSTREAM};
    proxy_pass $oauth2_upstream;
    proxy_pass_request_body off;
    proxy_set_header Content-Length "";
    proxy_set_header Host $host;
    proxy_set_header X-Forwarded-Proto $forwarded_proto;
    proxy_set_header X-Forwarded-Host $host;
    proxy_set_header X-Forwarded-Uri $request_uri;
  }
  location @oauth2_signin {
    return 302 "${authUrlOf(settings)}/oauth2/start?rd=$forwarded_proto://$http_host$request_uri";
  }`;

/**
 * nginx config for the optional preview proxy (compose/preview-proxy.yml):
 * one server block per slot that has a preview. Requests reach the slot's UI
 * on the host; the Host header is rewritten to the slot's own 127.0.0.1 origin,
 * which the dev server accepts. Redirects the app sends to its own loopback
 * origin (its FRONTEND_URL) are rewritten to the preview origin, so a person
 * stays on the preview host.
 */
export const routesConf = (
  routes: readonly IPreviewRoute[],
  settings: IPreviewSettings
): string => {
  const gated = settings.auth !== undefined;
  const blocks = [...routes]
    .sort((left, right) => left.slot - right.slot)
    .map((route) => {
      const previewUrl = previewUrlOf(route.slot, settings);

      return `server {
  listen 80;
  server_name ${route.host};
${gated ? `${authSlotLocations(settings)}\n` : ""}  location / {${gated ? `\n    auth_request /oauth2/auth;\n    error_page 401 = @oauth2_signin;` : ""}
    proxy_pass http://host.docker.internal:${String(route.uiPort)};
    proxy_http_version 1.1;
    proxy_set_header Host 127.0.0.1:${String(route.uiPort)};
    proxy_set_header Upgrade $http_upgrade;
    proxy_set_header Connection $connection_upgrade;
    proxy_set_header X-Forwarded-Host $host;
    proxy_read_timeout 3600s;
    proxy_redirect http://127.0.0.1:${String(route.uiPort)} ${previewUrl};
  }
}
`;
    });
  const authBlock = gated
    ? [
        "server {",
        "  listen 80;",
        `  server_name auth.${settings.domain};`,
        "  location /oauth2/ {",
        `    set $oauth2_upstream ${OAUTH2_UPSTREAM};`,
        "    proxy_pass $oauth2_upstream;",
        "    proxy_set_header Host $host;",
        "    proxy_set_header X-Forwarded-Proto $forwarded_proto;",
        "    proxy_set_header X-Forwarded-Host $host;",
        "    proxy_set_header X-Real-IP $remote_addr;",
        "    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;",
        "  }",
        "  location / { return 404; }",
        "}",
        "",
      ]
    : [];

  return [
    "# Generated by `bun run factory preview`. Do not edit.",
    "map $http_upgrade $connection_upgrade {",
    "  default upgrade;",
    "  ''      close;",
    "}",
    ...(gated ? [authHttpBlock] : []),
    "server {",
    "  listen 80 default_server;",
    "  server_name _;",
    '  location = /healthz { return 200 "ok\\n"; }',
    "  location / { return 404; }",
    "}",
    ...authBlock,
    ...blocks,
  ].join("\n");
};

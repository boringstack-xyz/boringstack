import { FACTORY_CONFIG } from "../factory.config";
import { previewHostOf, slotPorts } from "./paths.utils";

export interface IPreviewRoute {
  readonly slot: number;
  readonly host: string;
  readonly uiPort: number;
}

/** `http://s<N>.<previewHost>:<previewPort>` through the optional proxy. */
export const previewUrlOf = (slot: number): string =>
  `http://${previewHostOf(slot)}:${String(FACTORY_CONFIG.previewPort)}`;

/** The UI address a person opens directly, no proxy needed. */
export const directUrlOf = (slot: number): string =>
  `http://127.0.0.1:${String(slotPorts(slot).ui)}`;

/**
 * nginx config for the optional preview proxy (compose/preview-proxy.yml):
 * one server block per slot that has a preview. Requests reach the slot's UI
 * on the host; the Host header is rewritten to the slot's own 127.0.0.1 origin,
 * which the dev server accepts.
 */
export const routesConf = (routes: readonly IPreviewRoute[]): string => {
  const blocks = [...routes]
    .sort((left, right) => left.slot - right.slot)
    .map(
      (route) => `server {
  listen 80;
  server_name ${route.host};
  location / {
    proxy_pass http://host.docker.internal:${String(route.uiPort)};
    proxy_http_version 1.1;
    proxy_set_header Host 127.0.0.1:${String(route.uiPort)};
    proxy_set_header Upgrade $http_upgrade;
    proxy_set_header Connection $connection_upgrade;
    proxy_set_header X-Forwarded-Host $host;
    proxy_read_timeout 3600s;
  }
}
`
    );

  return [
    "# Generated by `bun run factory preview`. Do not edit.",
    "map $http_upgrade $connection_upgrade {",
    "  default upgrade;",
    "  ''      close;",
    "}",
    "server {",
    "  listen 80 default_server;",
    "  server_name _;",
    '  location = /healthz { return 200 "ok\\n"; }',
    "  location / { return 404; }",
    "}",
    ...blocks,
  ].join("\n");
};
